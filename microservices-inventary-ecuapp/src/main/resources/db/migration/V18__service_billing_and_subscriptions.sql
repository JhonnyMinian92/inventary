-- Services are sold once or by subscription (fixed plan of 1, 3, 6 or 12 months billed every 15 days, every 30 days or at the end).
ALTER TABLE product
 ADD COLUMN service_billing VARCHAR(16) CHECK (service_billing IN ('ONE_TIME','SUBSCRIPTION')),
 ADD COLUMN billing_frequency VARCHAR(16) CHECK (billing_frequency IN ('BIWEEKLY','MONTHLY','AT_END')),
 ADD COLUMN term_months INTEGER CHECK (term_months IN (1,3,6,12));
UPDATE product SET service_billing='ONE_TIME' WHERE product_kind='SERVICE';
ALTER TABLE product ADD CONSTRAINT ck_product_subscription_plan
 CHECK (service_billing IS DISTINCT FROM 'SUBSCRIPTION' OR (billing_frequency IS NOT NULL AND term_months IS NOT NULL));

-- Subscription invoices are regular sales generated by the system with their own channel.
DO $$
DECLARE c text;
BEGIN
 FOR c IN SELECT conname FROM pg_constraint WHERE conrelid='sale'::regclass AND contype='c' AND pg_get_constraintdef(oid) LIKE '%channel%' LOOP
  EXECUTE format('ALTER TABLE sale DROP CONSTRAINT %I', c);
 END LOOP;
END $$;
ALTER TABLE sale ADD CONSTRAINT ck_sale_channel CHECK (channel IN ('POS','WHATSAPP','WEB','MANUAL','SUBSCRIPTION'));

CREATE TABLE subscription (
 id UUID PRIMARY KEY,
 subscription_number VARCHAR(48) NOT NULL,
 status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','CANCELLED','COMPLETED')),
 customer_id UUID NOT NULL REFERENCES business_partner(id) ON DELETE RESTRICT,
 product_id UUID NOT NULL REFERENCES product(id) ON DELETE RESTRICT,
 warehouse_id UUID NOT NULL REFERENCES warehouse(id) ON DELETE RESTRICT,
 billing_frequency VARCHAR(16) NOT NULL CHECK (billing_frequency IN ('BIWEEKLY','MONTHLY','AT_END')),
 term_months INTEGER NOT NULL CHECK (term_months IN (1,3,6,12)),
 monthly_price NUMERIC(14,2) NOT NULL CHECK (monthly_price >= 0),
 total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
 currency VARCHAR(3) NOT NULL,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 prepaid BOOLEAN NOT NULL DEFAULT FALSE,
 prepaid_discount_percent NUMERIC(5,2) CHECK (prepaid_discount_percent BETWEEN 0 AND 100),
 prepaid_amount NUMERIC(14,2) CHECK (prepaid_amount >= 0),
 cancellation_reason VARCHAR(1000),
 cancelled_by VARCHAR(80),
 cancelled_at TIMESTAMPTZ,
 last_billing_error VARCHAR(500),
 created_by VARCHAR(80) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_subscription_number UNIQUE (subscription_number),
 CONSTRAINT ck_subscription_dates CHECK (end_date > start_date)
);
CREATE INDEX ix_subscription_customer ON subscription(customer_id, created_at DESC);
CREATE INDEX ix_subscription_status ON subscription(status, start_date);

CREATE TABLE subscription_installment (
 id UUID PRIMARY KEY,
 subscription_id UUID NOT NULL REFERENCES subscription(id) ON DELETE RESTRICT,
 sequence INTEGER NOT NULL CHECK (sequence > 0),
 period_start DATE NOT NULL,
 period_end DATE NOT NULL,
 billing_date DATE NOT NULL,
 amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
 status VARCHAR(16) NOT NULL CHECK (status IN ('SCHEDULED','INVOICED','CANCELLED')),
 sale_id UUID REFERENCES sale(id) ON DELETE RESTRICT,
 invoiced_at TIMESTAMPTZ,
 CONSTRAINT uk_subscription_installment_sequence UNIQUE (subscription_id, sequence),
 CONSTRAINT ck_subscription_installment_period CHECK (period_end > period_start),
 CONSTRAINT ck_subscription_installment_invoice CHECK ((status = 'INVOICED') = (sale_id IS NOT NULL))
);
CREATE INDEX ix_subscription_installment_due ON subscription_installment(status, billing_date);

